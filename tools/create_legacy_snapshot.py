"""Create the frozen ``legacy/python/`` snapshot and ``legacy/manifest.json``.

This is a one-time provenance tool (work package A, step 2). Files are
written byte-for-byte from git blobs at a fixed revision, so the archive does
not depend on working-tree line-ending conversion. Transient build artefacts
(bytecode caches and setuptools egg-info) are excluded from the executable
archive and recorded in the manifest with their hashes.

Usage (from the repository root)::

    python tools/create_legacy_snapshot.py --revision d69ab5f

The tool refuses to overwrite an existing snapshot unless ``--force`` is given.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import platform
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_PREFIX = "python/"
ARCHIVE_DIR = ROOT / "legacy" / "python"
MANIFEST = ROOT / "legacy" / "manifest.json"

EXCLUSION_RULES = (
    ("/__pycache__/", "CPython bytecode cache; regenerated by the interpreter and not part of the source."),
    (".egg-info/", "setuptools build metadata generated by an editable install; not part of the source."),
)


def git(*args: str) -> bytes:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True).stdout


def exclusion_reason(path: str) -> str | None:
    for marker, reason in EXCLUSION_RULES:
        if marker in "/" + path:
            return reason
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--revision", required=True)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    if ARCHIVE_DIR.exists() and not args.force:
        print(f"{ARCHIVE_DIR} already exists; refusing to overwrite.", file=sys.stderr)
        return 1

    revision = git("rev-parse", args.revision).decode().strip()
    listing = git("ls-tree", "-r", "--full-tree", revision, SOURCE_PREFIX).decode().splitlines()
    remote = git("config", "--get", "remote.origin.url").decode().strip()

    archived, excluded = [], []
    for line in listing:
        meta, path = line.split("\t", 1)
        _, kind, blob = meta.split()
        if kind != "blob":
            continue
        data = git("cat-file", "blob", blob)
        relative = path[len(SOURCE_PREFIX):]
        entry = {"path": relative, "sha256": hashlib.sha256(data).hexdigest(), "git_blob": blob, "bytes": len(data)}
        reason = exclusion_reason(relative)
        if reason:
            excluded.append({**entry, "reason": reason})
            continue
        target = ARCHIVE_DIR / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        archived.append(entry)

    manifest = {
        "schema": "crossflow-legacy-manifest/1",
        "solver_identity": {"name": "legacy", "version": f"0.1.0+{revision[:7]}"},
        "snapshot": {
            "source_repository": remote,
            "source_revision": revision,
            "source_path": SOURCE_PREFIX,
            "archived_path": "legacy/python/",
            "created": date.today().isoformat(),
            "method": "Written byte-for-byte from git blobs at source_revision by tools/create_legacy_snapshot.py.",
            "policy": "Frozen. No development or numerical fixes. Known defects are preserved intentionally.",
        },
        "files": archived,
        "excluded": excluded,
        "runtime": {
            "declared_requires_python": ">=3.10",
            "declared_dependencies": ["numpy", "matplotlib"],
            "effective_constraints": {
                "numpy": ">=2.0 (the archived physics module calls np.trapezoid)",
                "matplotlib": "only required by plotter.py; the solver worker does not import it",
            },
            "solver_modules": [
                "cross_section", "inlets", "operators", "physics", "lubrication", "pillars", "secondary_flow",
            ],
            "recorded_environment": {
                "python": platform.python_version(),
                "implementation": platform.python_implementation(),
                "platform": platform.platform(),
            },
        },
        "original_tests": {
            "path": "legacy/python/tests",
            "count": 6,
            "command": "python -m crossflow_simulator legacy-tests",
        },
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Archived {len(archived)} files, excluded {len(excluded)}; manifest at {MANIFEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
