"""Stable material colours and stream bookkeeping.

Colours are keyed by material ID (not by array value), so reordering inlets,
recolouring, or comparing backends never changes which colour a material
gets. The palette keeps more than eight materials distinguishable; beyond it,
colours are generated by golden-ratio hue stepping.
"""
from __future__ import annotations

import colorsys

from .config import ProjectConfig

# Okabe-Ito followed by Paul Tol's muted and light schemes (colour-vision-deficiency aware).
PALETTE = [
    "#0072B2", "#E69F00", "#009E73", "#CC79A7", "#56B4E9", "#D55E00", "#F0E442", "#000000",
    "#332288", "#88CCEE", "#44AA99", "#117733", "#999933", "#DDCC77", "#CC6677", "#882255",
    "#AA4499", "#77AADD", "#EE8866", "#BBCC33",
]
INVALID_COLOR = "#B0B0B0"
UNMATCHED_COLORS = ["#FF00FF", "#00FFFF", "#808000", "#800080"]


def palette_color(index: int) -> str:
    if index < len(PALETTE):
        return PALETTE[index]
    hue = (0.61803398875 * (index - len(PALETTE))) % 1.0
    r, g, b = colorsys.hls_to_rgb(hue, 0.5, 0.65)
    return "#{:02X}{:02X}{:02X}".format(int(r * 255), int(g * 255), int(b * 255))


def material_colors(cfg: ProjectConfig) -> dict[str, str]:
    return {m.id: (m.color or palette_color(i)) for i, m in enumerate(cfg.materials)}


def stream_table(cfg: ProjectConfig, rates: dict[str, float] | None = None) -> list[dict]:
    """One record per inlet: stable code, IDs, colours, flow rate, and fluid properties."""
    colors = material_colors(cfg)
    codes = cfg.stream_codes()
    records = []
    for index, inlet in enumerate(cfg.inlets):
        material = cfg.material(inlet.material)
        rate = rates.get(inlet.id) if rates is not None else inlet.flow_rate
        records.append({
            "code": codes[inlet.id],
            "inlet_id": inlet.id,
            "material_id": inlet.material,
            "enabled": inlet.enabled,
            "placement": inlet.placement,
            "flow_rate_m3_s": rate,
            "viscosity_Pa_s": material.viscosity,
            "density_kg_m3": material.density,
            "material_color": colors[inlet.material],
            "inlet_color": palette_color(index),
        })
    return records


def colors_for(streams: list[dict], by: str = "material") -> dict[int, str]:
    key = "material_color" if by == "material" else "inlet_color"
    out = {int(s["code"]): s[key] for s in streams}
    out[-1] = INVALID_COLOR
    return out
